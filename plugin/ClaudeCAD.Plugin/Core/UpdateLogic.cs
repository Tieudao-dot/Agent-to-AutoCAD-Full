using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Security.Cryptography;
using System.Text;

namespace ClaudeCAD.Plugin.Core
{
    /// <summary>Update manifest published next to each release (latest.json).</summary>
    public sealed class UpdateManifest
    {
        public Version Version;
        public string Url;
        public string Sha256;
        public string Notes;
        public string MinAutoCAD;
    }

    /// <summary>AutoCAD-independent parts of the auto-update (unit-tested).</summary>
    public static class UpdateLogic
    {
        public static readonly TimeSpan CheckInterval = TimeSpan.FromHours(24);

        /// <summary>
        /// Parses {"version": "0.4.0", "url": "https://.../ClaudeCAD-0.4.0.zip", "sha256": "...", "notes": "..."}.
        /// </summary>
        public static UpdateManifest ParseManifest(string json)
        {
            var d = JsonCodec.ParseObject(json);
            string Get(string k) => d.TryGetValue(k, out var v) ? v as string : null;
            var versionText = Get("version")?.Trim().TrimStart('v', 'V');
            if (string.IsNullOrEmpty(versionText) || !Version.TryParse(Normalize(versionText), out var version))
                throw new FormatException("update manifest: missing or invalid 'version'");
            var url = Get("url");
            if (string.IsNullOrEmpty(url) || !url.StartsWith("https://", StringComparison.OrdinalIgnoreCase))
                throw new FormatException("update manifest: 'url' must be an https:// link");
            var sha = Get("sha256")?.Trim().ToLowerInvariant();
            if (string.IsNullOrEmpty(sha) || sha.Length != 64 || !IsHex(sha))
                throw new FormatException("update manifest: 'sha256' must be 64 hex characters");
            return new UpdateManifest { Version = version, Url = url, Sha256 = sha, Notes = Get("notes") ?? "", MinAutoCAD = Get("min_autocad") };
        }

        /// <summary>"0.4" → "0.4.0"; keeps at most 4 numeric parts; drops a "-beta" suffix.</summary>
        public static string Normalize(string v)
        {
            int dash = v.IndexOfAny(new[] { '-', '+' });
            if (dash >= 0) v = v.Substring(0, dash);
            var parts = v.Split('.');
            if (parts.Length == 1) return v + ".0";
            return string.Join(".", parts, 0, Math.Min(4, parts.Length));
        }

        public static bool IsNewer(Version current, Version candidate) => candidate != null && current != null && Trim3(candidate) > Trim3(current);

        private static Version Trim3(Version v) => new Version(v.Major, Math.Max(0, v.Minor), Math.Max(0, v.Build));

        public static bool ShouldCheck(DateTime? lastCheckUtc, DateTime nowUtc) =>
            !lastCheckUtc.HasValue || nowUtc - lastCheckUtc.Value >= CheckInterval || lastCheckUtc.Value > nowUtc;

        public static string Sha256Hex(Stream s)
        {
            using (var sha = SHA256.Create())
            {
                var hash = sha.ComputeHash(s);
                var sb = new StringBuilder(64);
                foreach (var b in hash) sb.Append(b.ToString("x2", CultureInfo.InvariantCulture));
                return sb.ToString();
            }
        }

        private static bool IsHex(string s)
        {
            foreach (var c in s) if (!Uri.IsHexDigit(c)) return false;
            return true;
        }

        /// <summary>
        /// The Windows batch script that applies a staged bundle once AutoCAD has exited:
        /// waits for the process, mirrors program files, and adds new skill files without
        /// overwriting skills the user has edited.
        /// </summary>
        public static string ApplyScript(int acadPid, string stagedBundle, string installedBundle, string logFile)
        {
            var q = new Func<string, string>(p => "\"" + p + "\"");
            var sb = new StringBuilder();
            sb.AppendLine("@echo off");
            sb.AppendLine("rem ClaudeCAD updater: generated by the plugin, runs after AutoCAD closes");
            sb.AppendLine(":wait");
            sb.AppendLine($"tasklist /FI \"PID eq {acadPid}\" 2>nul | find \"{acadPid}\" >nul && (timeout /t 2 /nobreak >nul & goto wait)");
            sb.AppendLine($"echo %date% %time% applying update >> {q(logFile)}");
            // program files (everything except skills): mirror
            sb.AppendLine($"robocopy {q(stagedBundle)} {q(installedBundle)} /E /PURGE /XD {q(Path.Combine(stagedBundle, "Contents", "skills"))} {q(Path.Combine(installedBundle, "Contents", "skills"))} /R:5 /W:2 /NP >> {q(logFile)}");
            // skills: only add files that do not exist yet (keep user edits)
            sb.AppendLine($"robocopy {q(Path.Combine(stagedBundle, "Contents", "skills"))} {q(Path.Combine(installedBundle, "Contents", "skills"))} /E /XC /XN /XO /R:2 /W:1 /NP >> {q(logFile)}");
            sb.AppendLine($"rmdir /s /q {q(stagedBundle)}");
            sb.AppendLine($"echo %date% %time% update done >> {q(logFile)}");
            return sb.ToString();
        }
    }
}
